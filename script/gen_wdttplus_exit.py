"""Generate core/internal/relay/wdttplus_exit_scripts.go: the shell scripts of WDTT Plus's
«Выходной IP и прокси», byte for byte, as Go raw strings.

Source: qThroneMobile's deploy/WdttPlusExit.kt, itself a copy of WDTT-Plus ui/DeployTab.kt,
ExternalProxyDiagnostics.kt and OutboundProbe.kt at commit f706ccd. Every script is checked
against the WDTT-Plus sources before it is written. Kotlin interpolations become ⟦n⟧ markers
that exitScript fills in the order listed in each comment.

Usage: python script/gen_wdttplus_exit.py <WdttPlusExit.kt> <WDTT-Plus checkout>
"""
import re
import sys
from pathlib import Path

MARK_OPEN, MARK_CLOSE = '⟦', '⟧'


def tokenize(body):
    """Kotlin raw-string template -> (text with markers, interpolation expressions, kotlin text)."""
    out, exprs, i = [], [], 0
    while i < len(body):
        if body.startswith("${'$'}", i):
            out.append('$')
            i += 6
        elif body.startswith('${', i):
            end = body.index('}', i)
            exprs.append(body[i + 2:end])
            out.append(f'{MARK_OPEN}{len(exprs) - 1}{MARK_CLOSE}')
            i = end + 1
        elif body[i] == '$' and i + 1 < len(body) and (body[i + 1].isalpha() or body[i + 1] == '_'):
            m = re.match(r'[A-Za-z_][A-Za-z0-9_]*', body[i + 1:])
            exprs.append(m.group(0))
            out.append(f'{MARK_OPEN}{len(exprs) - 1}{MARK_CLOSE}')
            i += 1 + len(m.group(0))
        else:
            out.append(body[i])
            i += 1
    return ''.join(out), exprs


def main():
    kotlin = Path(sys.argv[1]).read_text(encoding='utf-8')
    plus = Path(sys.argv[2])
    originals = ''.join(p.read_text(encoding='utf-8') for p in plus.rglob('*.kt')
                        if p.name in ('DeployTab.kt', 'ExternalProxyDiagnostics.kt', 'OutboundProbe.kt'))
    # Numbered like every raw string of the file; Regex("""...""") patterns of the SSH plumbing are not scripts.
    raws = [(m.group(1), kotlin[max(0, m.start() - 6):m.start()] == 'Regex(') for m in re.finditer(r'"""(.*?)"""', kotlin, re.S)]
    lines = ['// Code generated by script/gen_wdttplus_exit.py; DO NOT EDIT.',
             '// The shell scripts of WDTT Plus «Выходной IP и прокси» (WDTT-Plus f706ccd: ui/DeployTab.kt,',
             '// ExternalProxyDiagnostics.kt, OutboundProbe.kt), byte for byte; ⟦n⟧ is the n-th interpolation.',
             '', 'package relay', '', 'var exitRaw = [...]string{']
    missing = []
    for n, (body, pattern) in enumerate(raws, 1):
        if pattern:
            continue
        text, exprs = tokenize(body)
        if MARK_OPEN in body or '`' in text:
            raise SystemExit(f'RAW{n}: marker or backtick inside the script')
        # The original keeps the same template text; its interpolations may name other variables.
        skeleton = re.sub(r'\$\{[^}]*\}|\$[A-Za-z_][A-Za-z0-9_]*', '\x00', body.replace("${'$'}", '\x01'))
        pieces = [piece.replace('\x01', "${'$'}") for piece in skeleton.split('\x00')]
        if not all(piece in originals for piece in pieces if piece.strip()):
            missing.append(n)
        lines.append(f'\t// RAW{n}: ' + (', '.join(exprs) if exprs else 'no interpolation'))
        lines.append(f'\t{n}: `{text}`,')
    lines.append('}')
    if missing:
        raise SystemExit(f'scripts not found in WDTT-Plus sources: {missing}')
    out = Path(__file__).resolve().parent.parent / 'core/internal/relay/wdttplus_exit_scripts.go'
    out.write_text('\n'.join(lines) + '\n', encoding='utf-8', newline='\n')
    print(f'{sum(not pattern for _, pattern in raws)} scripts written to {out}')


if __name__ == '__main__':
    main()
